// تولید src/theme-light.css
// ایده: رنگ‌ها در Tailwind v4 متغیر CSS هستند؛ فقط داخل کلاس .light مقدارشان عوض می‌شود.
// پس تم تیره دست نمی‌خورد و تم روشن سلسله‌مراتب رنگ‌ها را حفظ می‌کند.
//   - خاکستری‌ها (slate/zinc/gray/...) برعکس می‌شوند: 800 <-> 200 و ...
//   - رنگ‌های روشن متن (مثل amber-400) تیره‌تر می‌شوند تا روی سفید خوانا باشند
//   - رنگ‌های سطح (surface-*) به سه سطح روشن: زمینه / کارت / برجسته
//   - white به رنگ متن تبدیل می‌شود (bg-white/5 و border-white/10 خودکار درست می‌شوند)
//     و روی دکمه‌های رنگی دوباره سفید می‌شود.
// اجرا: node scripts/build-light-theme.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const themeCss = fs.readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');
const palette = {};
for (const m of themeCss.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (palette[m[1]] ||= {})[m[2]] = m[3].trim();

// --- surfaces from src/index.css @theme ---
const indexCss = fs.readFileSync(path.join(root, 'src/index.css'), 'utf8');
const surfaces = [...indexCss.matchAll(/--color-surface-([0-9a-f]{6}):\s*#([0-9a-fA-F]{6});/g)].map((m) => m[1]);

const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const ACCENTS = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
const BRIGHT = new Set(['orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky']);
const INVERT = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };

const INK = '#0f172a';
const LIGHT = { base: '#eef2f6', card: '#ffffff', raised: '#e2e8f0' };
const tier = (hex) => {
  const max = Math.max(...[0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16)));
  return max <= 0x16 ? LIGHT.base : max <= 0x28 ? LIGHT.card : LIGHT.raised;
};

const lightVars = [];
const keepVars = []; // برای بخش‌هایی که باید رنگ اصلی بماند (مثل فاکتور چاپی)
for (const n of NEUTRALS) for (const [k, v] of Object.entries(palette[n] || {})) {
  lightVars.push(`--color-${n}-${k}: ${palette[n][INVERT[k]]};`);
  keepVars.push(`--color-${n}-${k}: ${v};`);
}
for (const h of ACCENTS) {
  const p = palette[h];
  if (!p) continue;
  const map = BRIGHT.has(h) ? { 200: 800, 300: 800, 400: 700, 900: 100, 950: 50 } : { 200: 800, 300: 700, 400: 600, 900: 100, 950: 50 };
  for (const [from, to] of Object.entries(map)) {
    lightVars.push(`--color-${h}-${from}: ${p[to]};`);
    keepVars.push(`--color-${h}-${from}: ${p[from]};`);
  }
}
for (const s of surfaces) {
  lightVars.push(`--color-surface-${s}: ${tier(s)};`);
  keepVars.push(`--color-surface-${s}: #${s};`);
}
lightVars.push(`--color-white: ${INK};`, `--color-fg: ${INK};`);
keepVars.push('--color-white: #fff;', '--color-fg: #f7fafc;');

// عناصری با پس‌زمینه رنگی پررنگ: متن سفید بماند
const solid = [];
for (const h of ACCENTS) for (const k of [500, 600, 700, 800]) solid.push(`.bg-${h}-${k}`, `.from-${h}-${k}`);
const solidHover = [];
for (const h of ACCENTS) for (const k of [500, 600, 700]) solidHover.push(`.hover\\:bg-${h}-${k}:hover`);

const css = `/* AUTO-GENERATED by scripts/build-light-theme.mjs — do not edit by hand */
.light {
  color-scheme: light;
  ${lightVars.join('\n  ')}
}

/* متن سفید روی دکمه‌ها و برچسب‌های رنگی */
.light :is(${solid.join(', ')}),
.light :is(${solidHover.join(', ')}),
.light .peer:checked ~ .peer-checked\\:bg-blue-600 {
  --color-white: #fff;
}

/* بخش‌هایی که همیشه رنگ اصلی را نگه می‌دارند (فاکتور، پیش‌نمایش چاپ) */
.light .theme-keep {
  ${keepVars.join('\n  ')}
}
`;
fs.writeFileSync(path.join(root, 'src/theme-light.css'), css);
console.log(`theme-light.css: ${lightVars.length} variables, ${surfaces.length} surfaces`);
